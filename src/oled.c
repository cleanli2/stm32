void IIC_write(unsigned char date)
{
	unsigned char i, temp;
	temp = date;
			
	for(i=0; i<8; i++)
	{	IIC_SCK_0;
		
        if ((temp&0x80)==0)
            IIC_SDA_0;
        else IIC_SDA_1;
		temp = temp << 1;
		//delay_us(1);			  
		IIC_SCK_1;
		//delay_us(1);
		
	}
	IIC_SCK_0;
	//delay_us(1);
	IIC_SDA_1;
	//delay_us(1);
	IIC_SCK_1;
//								不需要应答
//	if (READ_SDA==0)
//		ACK = 1;
//	else ACK =0;
	//delay_us(1);
	IIC_SCK_0;
	//delay_us(1);
	

}
