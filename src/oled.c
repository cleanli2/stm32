//SCL在高电平期间，SDA由高电平向低电平的变化定义为启动信号
void IIC_start()
{
	IIC_SDA_1;
	//delay_us(1);
	IIC_SCK_1;
	//delay_us(1);				   //所有操作结束释放SCL	
	IIC_SDA_0;
	//delay_us(3);
	IIC_SCK_0;
	
        IIC_write(0x78);
        
}

//停止信号
//SCL在高电平期间，SDA由低电平向高电平的变化定义为停止信号
void IIC_stop()
{
	IIC_SDA_0;
	//delay_us(1);
	IIC_SCK_1;
	//delay_us(3);
	IIC_SDA_1;
	
}

void OLED_send_cmd(unsigned char o_command)
  {
    
    IIC_start();
    IIC_write(0x00); 
    IIC_write(o_command);
    IIC_stop();
    
  }
void OLED_send_data(unsigned char o_data)
  { 
    IIC_start();
    IIC_write(0x40);
    IIC_write(o_data);
    IIC_stop();
   }
void Column_set(unsigned char column)
{
    OLED_send_cmd(0x10|(column>>4));    //high
    OLED_send_cmd(0x00|(column&0x0f));   //low

}
void Page_set(unsigned char page)
{
    OLED_send_cmd(0xb0+page);
}
void OLED_clear(void)
{
    unsigned char page,column;
    for(page=0;page<8;page++)             //page loop
    { 
        Page_set(page);
        Column_set(0);	  
        for(column=0;column<128;column++)	//column loop
        {
            OLED_send_data(0x00);
        }
    }
}
void OLED_full(void)
{
    unsigned char page,column;
    for(page=0;page<8;page++)             //page loop
    { 
        Page_set(page);
        Column_set(0);	  
        for(column=0;column<128;column++)	//column loop
        {
        oled_delayms(3000);
            OLED_send_data(0xff);
        }
    }
}

void Picture_display(const unsigned char *ptr_pic)
  {
    unsigned char page,column;
    for(page=0;page<(64/8);page++)        //page loop
      { 
	Page_set(page);
	Column_set(0);	  
	for(column=0;column<128;column++)	//column loop
          {
            OLED_send_data(*ptr_pic++);
          }
      }
  }
void Picture_ReverseDisplay(const unsigned char *ptr_pic)
{
    unsigned char page,column,data;
    for(page=0;page<(64/8);page++)        //page loop
      { 
	Page_set(page);
	Column_set(0);	  
	for(column=0;column<128;column++)	//column loop
          {
            data=*ptr_pic++;
            data=~data;
            OLED_send_data(data);
          }
      }
  }

void OLED_init(void)
{
    unsigned char i;
    for(i=0;i<25;i++)
    {
        OLED_send_cmd(OLED_init_cmd[i]);
    }
}

void oled_putasc(int page, int column, char c)
{
    int pos;
    uint8_t idx=(uint8_t)c-' ';

    Page_set(page);
    Column_set(column);

    const int size=16;
    for(pos=0;pos<size;pos++)
    {
        OLED_send_data(asc2_1608[idx][pos]);
    }
}
int oled_show()
{
    OLED_init();
    OLED_full();
    oled_putasc(1, 20, 'U');
    return 0;
}
